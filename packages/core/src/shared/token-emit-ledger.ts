/** Compile-time guard: a zod enum that drifts from its TS union would fail validation at runtime. */
type Exact<A, B> = [A] extends [B] ? ([B] extends [A] ? true : never) : never;

export const tokenEmitFormatSchema = z.enum(["css", "scss", "tailwind-v3", "tailwind-v4", "ts"]);
const _formatsInStep: Exact<TokenEmitFormat, z.infer<typeof tokenEmitFormatSchema>> = true;

export const tokenEmitDispositionSchema = z.enum([
  "create",
  "update",
  "unchanged",
  "kept",
  "diverged",
]);
const _dispositionsInStep: Exact<
  TokenEmitDisposition,
  z.infer<typeof tokenEmitDispositionSchema>
> = true;

export const emittedFileRoleSchema = z.enum(["token-file", "custom-properties"]);
const _rolesInStep: Exact<EmittedFile["role"], z.infer<typeof emittedFileRoleSchema>> = true;

/** `skipped` is deliberately absent — it is an INGEST-tail outcome (`tokenEmitSummarySchema`), not
 *  something a direct emit can return: a direct emit that cannot run throws, by design. */
export const tokenEmitStatusSchema = z.enum(["written", "up-to-date", "diverged", "read-only"]);

export const tokenEmitFileReportSchema = z.object({
  /** Project-relative POSIX path. */
  path: z.string(),
  role: emittedFileRoleSchema,
  disposition: tokenEmitDispositionSchema,
});

export const tokenEmitResultSchema = z.object({
  status: tokenEmitStatusSchema,
  styling: z.string(),
  format: tokenEmitFormatSchema,
  files: z.array(tokenEmitFileReportSchema).default([]),
  written: z.array(z.string()).default([]),
  diverged: z.array(z.string()).default([]),
  kept: z.array(z.string()).default([]),
  message: z.string().optional(),
});
export type TokenEmitStatus = z.infer<typeof tokenEmitStatusSchema>;
export type TokenEmitFileReport = z.infer<typeof tokenEmitFileReportSchema>;
export type TokenEmitResult = z.infer<typeof tokenEmitResultSchema>;
